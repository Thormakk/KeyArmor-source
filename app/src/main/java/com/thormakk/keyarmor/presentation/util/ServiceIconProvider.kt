    private val packagePrefixes = setOf("com", "org", "net", "io", "app", "me", "co", "ar", "es")

    private fun packageBrandHost(host: String): String? {
        val parts = host.split(".")
        if (parts.size < 3 || parts[0] !in packagePrefixes) return null
        val brand = parts[1]
        if (brand.length < 3 || brand == "android") return null
        return "$brand.com"
    }

    fun bestUrl(urls: List<String>): String =
        urls.firstOrNull { resolveIcon(it) != null } ?: urls.firstOrNull() ?: ""

    fun resolveByName(name: String): Icon? {
        if (name.isBlank()) return null
        return nameEntries[name.trim().lowercase()]
    }

    private fun matchesDomain(hostname: String, pattern: String): Boolean = when {
        pattern.endsWith(".")  -> hostname.startsWith(pattern)
        else                   -> hostname == pattern
                               || hostname.endsWith(".$pattern")
    }

    private fun normalize(url: String): String? {
        if (url.isBlank()) return null
        return url.trim().lowercase()
            .removePrefix("https://")
            .removePrefix("http://")
            .removePrefix("www.")
    }
