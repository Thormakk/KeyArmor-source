    )

    fun resolveIcon(url: String): Icon? {
        val normalized = normalize(url) ?: return null
        val hostname   = normalized.split("/").first()
        resolveHost(hostname)?.let { return it }
        packageDomains[hostname]?.let { d -> resolveHost(d)?.let { return it } }
        packageBrandHost(hostname)?.let { return resolveHost(it) }
        return null
    }

    private fun resolveHost(hostname: String): Icon? {
        for ((res, color, domains, tinted, iconSizeDp) in entries) {
            if (domains.any { matchesDomain(hostname, it) })
                return Icon(res, color, tinted = tinted, isAppIcon = res == R.mipmap.ic_launcher, iconSizeDp = iconSizeDp)
        }
        return null
    }

